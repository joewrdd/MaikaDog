    test(
      'fires once for a long run that goes quiet ending in assistant',
      () async {
        final file = writeSession(
          '-Users-t-Desktop-alpha',
          'aaaa1111.jsonl',
          cwd: '/Users/t/Desktop/alpha',
          branch: 'main',
          prompt: 'Fix the login flow',
        );
        final sidekick = makeSidekick(
          completionQuietMin: const Duration(milliseconds: 100),
          completionMinRun: const Duration(milliseconds: 200),
        );
        sidekick.scanOnce();
        expect(sidekick.anyWorking, isTrue);
        await Future<void>.delayed(const Duration(milliseconds: 250));
        file.writeAsStringSync(
          '${_assistantLine('/Users/t/Desktop/alpha', 'main', 'All fixed.')}\n'
          '${_tailLines('/Users/t/Desktop/alpha', 'main')}\n',
          mode: FileMode.append,
          flush: true,
        );
        sidekick.scanOnce();
        await Future<void>.delayed(const Duration(milliseconds: 150));
        sidekick.scanOnce();
        sidekick.scanOnce();
        expect(ofType(SidekickEvent.completed), [
          (SidekickEvent.completed, 'alpha'),
        ]);
        expect(ofType(SidekickEvent.needsInput), isEmpty);
        expect(ofType(SidekickEvent.error), isEmpty);
      },
    );

