typedef Captured = (SidekickEvent event, String label);

Map<String, dynamic> _base(String cwd, String branch, [String? at]) => {
  'parentUuid': null,
  'isSidechain': false,
  'userType': 'external',
  'cwd': cwd,
  'sessionId': 'aaaa1111-2222-3333-4444-555566667777',
  'version': '2.1.39',
  'gitBranch': branch,
  'timestamp': at ?? DateTime.now().toUtc().toIso8601String(),
  'uuid': 'eec2ece2-79c8-4808-979d-7a27565cb506',
};

String _userLine(String cwd, String branch, Object content, [String? at]) =>
    jsonEncode({
      ..._base(cwd, branch, at),
      'type': 'user',
      'message': {'role': 'user', 'content': content},
    });

String _assistantLine(
  String cwd,
  String branch,
  String text, {
  int cacheRead = 19885,
  String? at,
  String stop = 'end_turn',
}) => jsonEncode({
  ..._base(cwd, branch, at),
  'type': 'assistant',
  'requestId': 'req_011CRJyBmRE2',
  'message': {
    'id': 'msg_01Vv7Z2AbcD',
    'type': 'message',
    'role': 'assistant',
    'model': 'claude-fable-5',
    'content': [
      {'type': 'text', 'text': text},
    ],
    'stop_reason': stop,
    'usage': {
      'input_tokens': 2,
      'cache_creation_input_tokens': 21311,
      'cache_read_input_tokens': cacheRead,
      'output_tokens': 3139,
    },
  },
});

const _header =
    '{"type":"ai-title","aiTitle":"Test session","sessionId":"aaaa1111"}\n'
    '{"type":"mode","mode":"normal","sessionId":"aaaa1111"}\n'
    '{"type":"permission-mode","permissionMode":"default","sessionId":"aaaa1111"}\n'
    '{"type":"file-history-snapshot","messageId":"m1","snapshot":{"messageId":"m1","trackedFileBackups":{},"timestamp":"2026-07-15T08:24:32.703Z"},"isSnapshotUpdate":false}';

String _metaUserLines(String cwd, String branch) => [
  _userLine(
    cwd,
    branch,
    '<local-command-caveat>Caveat: The messages below were generated by the '
    'user while running local commands. DO NOT respond to these messages.'
    '</local-command-caveat>',
  ),
  _userLine(
    cwd,
    branch,
    '<command-name>/model</command-name>\n'
    '            <command-message>model</command-message>',
  ),
  _userLine(
    cwd,
    branch,
    '<local-command-stdout>Set model to Fable 5</local-command-stdout>',
  ),
].join('\n');

String _tailLines(String cwd, String branch, [String? at]) =>
    '${jsonEncode({..._base(cwd, branch, at), 'type': 'system', 'subtype': 'turn_duration', 'durationMs': 12345, 'isMeta': true, 'content': ''})}\n'
    '{"type":"last-prompt","leafUuid":"266e09d0-6ccb-4421-a3f6-86de436d51f1","sessionId":"aaaa1111"}';

String _sessionDoc({
  required String cwd,
  required String branch,
  required String prompt,
  String? firstUserContent,
  String? at,
}) {
  final lines = [
    _header,
    _metaUserLines(cwd, branch),
    if (firstUserContent != null) _userLine(cwd, branch, firstUserContent, at),
    _userLine(cwd, branch, prompt, at),
    _assistantLine(cwd, branch, 'On it.', at: at),
    _userLine(cwd, branch, [
      {'type': 'tool_result', 'tool_use_id': 'toolu_1', 'content': 'ok'},
    ], at),
    _assistantLine(cwd, branch, 'Done.', at: at),
    _tailLines(cwd, branch, at),
  ];
  return '${lines.join('\n')}\n';
}

void main() {
  late Directory tmp;
  late List<Captured> events;

  setUp(() {
    tmp = Directory.systemTemp.createTempSync('sidekick_test');
    events = [];
  });

  tearDown(() {
    tmp.deleteSync(recursive: true);
  });

  void collect(SidekickEvent event, String label) => events.add((event, label));

  Sidekick makeSidekick({
    String? Function()? frontApp,
    Map<String, int>? Function()? liveProbe,
    Duration workingWindow = const Duration(seconds: 15),
    Duration completionQuietMin = const Duration(seconds: 20),
    Duration completionMinRun = const Duration(seconds: 90),
    Duration nagQuietMin = const Duration(seconds: 45),
    Duration nagQuietMax = const Duration(minutes: 10),
    Duration nagMinRun = const Duration(seconds: 10),
  }) => Sidekick(
    collect,
    projectsDirOverride: tmp.path,
    frontAppOverride: frontApp ?? () => null,
    liveProbeOverride: liveProbe,
    announceAfter: const Duration(hours: 1),
    workingWindow: workingWindow,
    completionQuietMin: completionQuietMin,
    completionMinRun: completionMinRun,
    nagQuietMin: nagQuietMin,
    nagQuietMax: nagQuietMax,
    nagMinRun: nagMinRun,
  );

  File writeSession(
    String projectDir,
    String fileName, {
    required String cwd,
    required String branch,
    required String prompt,
    String? firstUserContent,
    String? at,
  }) {
    final dir = Directory('${tmp.path}/$projectDir')
      ..createSync(recursive: true);
    return File('${dir.path}/$fileName')..writeAsStringSync(
      _sessionDoc(
        cwd: cwd,
        branch: branch,
        prompt: prompt,
        firstUserContent: firstUserContent,
        at: at,
      ),
      flush: true,
    );
  }

  List<Captured> ofType(SidekickEvent type) =>
      events.where((e) => e.$1 == type).toList();

